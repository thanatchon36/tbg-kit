def rows(p: Path) -> str:
    if p.suffix != ".csv":
        return ""
    with p.open(encoding="utf-8-sig") as fh:
        return f"{sum(1 for _ in fh) - 1:,}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="demo", help="synthetic workspace (default: demo)")
    ap.add_argument("--out", default="dist/hf")
    a = ap.parse_args()
    src, out = (ROOT / a.src).resolve(), (ROOT / a.out).resolve()
    if not (src / "data/manual/synthetic_info.json").exists():
        raise SystemExit(f"{src} is not a synthetic workspace (no synthetic_info.json): refusing to publish it")
    if out.exists():
        shutil.rmtree(out)
    for f in FILES:
        (out / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src / f, out / f)

    s = json.loads((src / "results/summary.json").read_text(encoding="utf-8"))
    summary = "\n".join([
        f"- {s['n_entities']:,} entities: {s['n_listed']:,} listed firms, {s['n_companies']:,} companies, "
        f"{s['n_persons']:,} persons in {s['n_families']:,} families, {s['n_foreign']:,} foreign companies",
        f"- {s['n_holdings']:,} ownership edges and {s['n_board_seats']:,} board seats",
        f"- {s['n_groups_multi']:,} multi-firm business groups, {s['n_groups_multi_listed']:,} with several listed firms",
        f"- At the 20% threshold, {s['share_uo_family_20']:.0%} of listed firms are family-controlled, "
        f"{s['share_uo_wh_20']:.0%} widely held, {s['share_uo_state_20']:.0%} state, "
        f"{s['share_uo_unresolved_20']:.0%} unresolved",
    ])
    table = "\n".join(f"| `{f}` | {rows(out / f)} | {DESC[f]} |" for f in FILES)
    (out / "README.md").write_text(CARD.replace("{summary}", summary).replace("{table}", table), encoding="utf-8")
    (out / "LICENSE").write_text(
        "Data in this repository: Creative Commons Attribution 4.0 International (CC BY 4.0)\n"
        "https://creativecommons.org/licenses/by/4.0/\n\n"
        "All records are synthetic, generated by tbg-kit (MIT License, https://github.com/thanatchon36/tbg-kit).\n",
        encoding="utf-8")
    sums = [f"{hashlib.sha256((out / f).read_bytes()).hexdigest()}  {f}" for f in FILES]
    (out / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")
    print(f"wrote {len(FILES)} files + README.md, LICENSE, SHA256SUMS to {out}")


if __name__ == "__main__":
    main()
